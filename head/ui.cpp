void drawCyr(int x, int y, uint16_t cp, uint16_t color, uint8_t scale) {
    const uint8_t* g = NULL;
    if (cp >= 0x430 && cp <= 0x44F) g = cyrFont[cp - 0x430];
    else if (cp >= 0x410 && cp <= 0x42F) g = cyrUpFont[cp - 0x410];
    if (!g) return;
    for (int r = 0; r < 7; r++)
        for (int b = 0; b < 5; b++)
            if (g[r] & (1 << (4 - b)))
                disp->fillRect(x + b * scale, y + r * scale, scale, scale, color);
}

void drawUtf8(int x, int y, const String& s, uint16_t color, uint8_t scale) {
    int cx = x; size_t i = 0;
    disp->setTextColor(color); disp->setTextSize(1);
    if (scale == 1) disp->setFont(nullptr);
    else            disp->setFont(&FreeSans9pt7b);
    while (i < s.length()) {
        uint8_t c = s[i];
        if (c < 0x80) {
            disp->setCursor(cx, y + (scale == 1 ? 0 : 12));
            disp->print((char)c);
            cx = disp->getCursorX(); i++;
        } else {
            uint16_t cp = ((c & 0x1F) << 6) | (s[i + 1] & 0x3F);
            drawCyr(cx, y + (scale == 1 ? 0 : 2), cp, color, scale);
            cx += 6 * scale; i += 2;
        }
    }
    disp->setFont(nullptr);
}

String utf8At(const String& s, int idx) {
    int n = 0; size_t i = 0;
    while (i < s.length()) {
        if (n == idx) { uint8_t c = s[i]; return (c < 0x80) ? s.substring(i, i + 1) : s.substring(i, i + 2); }
        i += (s[i] < 0x80) ? 1 : 2; n++;
    }
    return "";
}