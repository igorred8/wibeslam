static const uint8_t SEG7[10] = {0x3F,0x06,0x5B,0x4F,0x66,0x6D,0x7D,0x07,0x7F,0x6F};
void wSegChar(int x, int y, int u, char c, uint16_t col) {
    uint8_t m = 0;
    if (c >= '0' && c <= '9') m = SEG7[c - '0'];
    else if (c == '-') m = 0x40;
    else if (c == '.') { disp->fillRect(x + u, y + 7 * u, 2 * u, 2 * u, col); return; }
    else return;
    if (m & 0x01) disp->fillRect(x + u, y, 4 * u, u, col);
    if (m & 0x02) disp->fillRect(x + 5 * u, y + u, u, 3 * u, col);
    if (m & 0x04) disp->fillRect(x + 5 * u, y + 5 * u, u, 3 * u, col);
    if (m & 0x08) disp->fillRect(x + u, y + 8 * u, 4 * u, u, col);
    if (m & 0x10) disp->fillRect(x, y + 5 * u, u, 3 * u, col);
    if (m & 0x20) disp->fillRect(x, y + u, u, 3 * u, col);
    if (m & 0x40) disp->fillRect(x + u, y + 4 * u, 4 * u, u, col);
}
void wBigNumber(int x, int y, int u, const char* s, uint16_t col) {
    int cx = x;
    for (const char* p = s; *p; p++) {
        wSegChar(cx, y, u, *p, col);
        cx += (*p == '.') ? 4 * u : 8 * u;
    }
}

