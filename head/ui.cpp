uint16_t lerpColor(uint16_t c1, uint16_t c2, uint8_t t) {
    int r1=(c1>>11)&31, g1=(c1>>5)&63, b1=c1&31;
    int r2=(c2>>11)&31, g2=(c2>>5)&63, b2=c2&31;
    return ((r1+((r2-r1)*t)/255)<<11) | ((g1+((g2-g1)*t)/255)<<5) | (b1+((b2-b1)*t)/255);
}

void osdPrintf(int16_t x, int16_t y, uint8_t size, uint16_t color, const char* fmt, ...) {
    char buf[128]; va_list ap; va_start(ap, fmt);
    vsnprintf(buf, sizeof(buf), fmt, ap); va_end(ap);
    disp->setTextColor(color); disp->setTextSize(1);
    if (size == 1)      { disp->setFont(nullptr);         disp->setCursor(x, y); }
    else if (size == 2) { disp->setFont(&FreeSans9pt7b);  disp->setCursor(x, y + 12); }
    else                { disp->setFont(&FreeSans12pt7b); disp->setCursor(x, y + 16); }
    disp->print(buf);
    disp->setFont(nullptr);
}

